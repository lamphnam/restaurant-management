async function login(page, phone, route) {
  await page.goto(`${base}/login`)
  await page.getByLabel('Số điện thoại', { exact: true }).fill(phone)
  await page.getByLabel('Mật khẩu', { exact: true }).fill(process.env.DEMO_PASSWORD ?? 'Demo@123')
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click()
  await page.waitForURL(`${base}${route}`)
}
async function logout(page) { await page.getByRole('button', { name: 'Đăng xuất', exact: true }).click(); await page.waitForURL(`${base}/login`) }
async function noOverflow(page, description) { assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)); pass(description) }
async function api(page, method, url, body) {
  const token = await page.evaluate(() => JSON.parse(localStorage.getItem('restaurant.session')).accessToken)
  const response = await page.request.fetch(`${base}/api${url}`, { method, data: body, headers: { Authorization: `Bearer ${token}` } })
  assert.equal(response.status(), 200, `${method} ${url}`)
  return response.json()
}
